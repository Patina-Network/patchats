    /** Every pair of members matched in any past cycle, regardless of match status. */
    public static Set<Set<UUID>> pastPairs() {
        Set<Set<UUID>> pairs = new HashSet<>();
        for (Match match : MATCHES) {
            pairs.add(Set.of(match.getMemberAId(), match.getMemberBId()));
        }
        return pairs;
    }

    /** Mock member IDs follow {@code 10000000-0000-4000-8000-<n padded to 12 digits>}. */
    public static UUID memberId(int n) {
        return UUID.fromString(String.format("10000000-0000-4000-8000-%012d", n));
    }

    private static Instant runAt(String period) {
        return Instant.parse(period + "-01T14:00:00Z");
    }

    private static Member member(
            int n,
            String firstName,
            String lastName,
            String email,
            boolean active,
            String matchPref,
            String industryPref,
            String rolePref,
            String topics,
            String introduction,
            String extraNotes) {
        return Member.builder()
                .id(memberId(n))
                .firstName(firstName)
                .lastName(lastName)
                .email(email)
                .active(active)
                .matchPref(matchPref)
                .industryPref(industryPref)
                .rolePref(rolePref)
                .topics(topics)
                .introduction(introduction)
                .extraNotes(extraNotes)
                .build();
    }

    private static MatchCycle cycle(int id, String period) {
        return MatchCycle.builder()
                .id(id)
                .period(period)
                .runAt(runAt(period))
                .isDraft(false)
                .build();
    }

    private static Match match(
            String id, int cycleId, String period, int memberA, int memberB, double score, MatchStatus status) {
        return Match.builder()
                .id(UUID.fromString(id))
                .memberAId(memberId(memberA))
                .memberBId(memberId(memberB))
                .matchCycleId(cycleId)
                .period(period)
                .matchScore(score)
                .status(status)
                .createdAt(runAt(period))
                .build();
    }
